#include "3-calc.h"
/**
 * op_add - return an addrition
 * @a: int to add
 * @b: int to add
 *
 * Return: int
 */
int op_add(int a, int b)
{
	return (a + b);
}
/**
 * op_sub - return an subtraction
 * @a: int to subtract
 * @b: int to subtract
 *
 * Return: int
 */
int op_sub(int a, int b)
{
	return (a - b);
}
/**
 * op_mul - return a multiplication
 * @a: int to multiply
 * @b: int to multiply
 *
 * Return: int
 */
int op_mul(int a, int b)
{
	return (a * b);
}
/**
 * op_div - return a division
 * @a: int to divide
 * @b: int to divide
 *
 * Return: int
 */
int op_div(int a, int b)
{
	return (a / b);
}
/**
 * op_mod - return the reminder
 * @a: int to divide
 * @b: int to divide
 *
 * Return: int
 */
int op_mod(int a, int b)
{
	return (a % b);
}

